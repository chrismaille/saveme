function normalizeLanguage(value) {
    const raw = String(value || '').replace('-', '_');
    if (!raw)
        return '';
    const lower = raw.toLowerCase();
    if (lower === 'pt' || lower.startsWith('pt_'))
        return 'pt_BR';
    if (lower === 'no' || lower.startsWith('nb'))
        return 'nb';
    const short = lower.split('_')[0];
    if (short === 'nb' || short === 'no')
        return 'nb';
    return SUPPORTED_LANGUAGES.includes(short) ? short : '';
}

function detectLanguage() {
    for (const name of GLib.get_language_names()) {
        const language = normalizeLanguage(name);
        if (language)
            return language;
    }
    return 'en';
}

let currentLanguage = detectLanguage();

export function setLanguage(value) {
    if (!value || value === 'system') {
        currentLanguage = detectLanguage();
        return currentLanguage;
    }
    currentLanguage = normalizeLanguage(value) || 'en';
    return currentLanguage;
}

export function t(message, replacements = {}) {
    const catalog = CATALOGS[currentLanguage] || {};
    let text = catalog[message] || message;
    for (const [key, value] of Object.entries(replacements))
        text = text.replaceAll(`{${key}}`, String(value));
    return text;
}
